      const hay = (e.slug + ' ' + e.summary + ' ' + e.project + ' ' + e.module).toLowerCase();
      if (!hay.includes(search)) return false;
    }
    return true;
  });

  const states = [
    {key:'proposed', label:'Proposed (draft plans, not ready)'},
    {key:'todo',     label:'Todo (ready to implement)'},
    {key:'current',  label:'Current (how the system works now)'},
