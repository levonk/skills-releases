      html += '<div class="proj-group"><div class="proj-name">' + proj + '</div>';
      const projEntries = entries.filter(e => e.project === proj);
      const modules = [...new Set(projEntries.map(e => e.module))].sort();
      for (const mod of modules) {
        html += '<div class="module-group"><div class="module-name">' + mod + '</div>';
        const modEntries = projEntries.filter(e => e.module === mod);
        for (const e of modEntries) {
          const badgeClass = 'badge-' + (e.status === 'superseded' ? 'superseded' : e.state);
          html += '<div class="entry">';
          html += '<a href="' + e.path + '">' + e.slug + '</a> ';
          html += '<span class="badge ' + badgeClass + '">' + e.status + '</span>';
          html += ' <span class="summary">' + e.summary + '</span>';
          html += '</div>';
        }
        html += '</div>';
      }
      html += '</div>';
    }
    html += '</div>';
  }

  if (!html) {
    html = '<div class="empty">No requirements match the current filters.</div>';
  }

  document.getElementById('content').innerHTML = html;
}
